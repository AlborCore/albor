TEST(PngDecoderChecks, ConvertsSixteenBitGrayToRgba) {
    // arrange
    constexpr std::uint8_t GRAY16_PNG[] = {
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x10, 0x00, 0x00, 0x00, 0x00, 0x6A, 0xEE, 0x47, 0x16, 0x00, 0x00, 0x00, 0x0B, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x68, 0x60, 0x00, 0x00, 0x01, 0x03, 0x00, 0x81, 0x3E, 0x4C, 0xC5, 0x93, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    };
    // act
    const std::optional<albor::resources::DecodedPixels> decoded = albor::resources::decode_png(GRAY16_PNG);
    // assert
    ASSERT_TRUE(decoded.has_value());
    EXPECT_EQ(decoded->width, 1u);
    EXPECT_EQ(decoded->height, 1u);
    ASSERT_EQ(decoded->rgba.size(), 4u);
    EXPECT_EQ(decoded->rgba[0], decoded->rgba[1]);
    EXPECT_EQ(decoded->rgba[1], decoded->rgba[2]);
    EXPECT_GT(decoded->rgba[0], 0u);
    EXPECT_EQ(decoded->rgba[3], 255u);
}
